// declaração com let, const e tipos de valores.


console.log("=== VARIÁVEIS EM JAVASCRIPT ===");

// 1. Declarando uma variável com let
let idade = 25;

console.log("Idade:", idade);

// Podemos alterar o valor de uma variável let
idade = 26;

console.log("Nova idade:", idade);

// 2. Declarando uma constante com const
const nome = "Mariana";

console.log("Nome:", nome);

// Uma constante não pode receber outro valor depois da inicialização.
// nome = "Ana"; // Descomente para observar o erro.

// 3. Outros exemplos de valores
const cidade = "Recife";
const quantidade = 10;
const matriculada = true;

console.log("Cidade:", cidade);
console.log("Quantidade:", quantidade);
console.log("Matriculada:", matriculada);
